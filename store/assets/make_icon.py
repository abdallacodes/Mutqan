#!/usr/bin/env python3
"""
Generates Mutqan's launcher icon from one set of numbers, so every size and format stays identical:

  store/assets/icon.svg                          the icon, full-bleed (rendered to icon-512.png for the Play listing)
  app/src/main/res/drawable/ic_launcher_*.xml    the adaptive icon: background, foreground, monochrome (themed icons)
  app/src/main/res/mipmap-*/ic_launcher*.webp    the icon for Android 7.0 and 7.1 (before adaptive icons)
  store/assets/feature.html                      the Play feature graphic (1024x500), which carries the same mark

The mark is the eight-pointed star that marks a quarter of a hizb: two squares, one cream and one gold, woven over
and under each other, on the deep green of the Paper palette (ui/theme/Color.kt). Run it from anywhere:

    python store/assets/make_icon.py

Then render the PNGs with Chrome (see store/assets/README.md). Needs Pillow only for the legacy icons.
"""
import io
import math
import os
import subprocess
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CHROME = r"C:\Program Files\Google\Chrome\Application\chrome.exe"

BG, GLOW = "#14463A", "#1F5A4A"          # deep green, and the soft disc behind the mark
CREAM, GOLD, EDGE = "#F4EDDC", "#D4A94C", "#0A2A21"

C = 54.0                                  # centre of the 108 x 108 canvas
R = 28.0                                  # distance from the centre to each point of the star (the safe zone is 33)
H = R / math.sqrt(2)                      # half the side of the cream square
BAND, OUTLINE = 4.2, 6.0                  # width of a band, and of the dark edge drawn under it
PATCH = 5.2                               # half the length of a woven crossing


def f(x):
    return ("%.2f" % x).rstrip("0").rstrip(".")


def pts(points):
    return " ".join(f(x) + "," + f(y) for x, y in points)


def path(points):
    return "M" + " L".join(f(x) + "," + f(y) for x, y in points) + " Z"


# The gold diamond and the cream square.
DIAMOND = [(C, C - R), (C + R, C), (C, C + R), (C - R, C)]
SQUARE = [(C - H, C - H), (C + H, C - H), (C + H, C + H), (C - H, C + H)]

# The four crossings where gold passes over cream: (x, y, angle of the gold band there).
CROSSINGS = []
for sx, sy, angle in ((1, -1, 45), (1, 1, -45), (-1, 1, 45), (-1, -1, -45)):
    # on the square's side x = C +- H the diamond is at |y - C| = R - H; the crossings alternate round the star
    if (sx, sy) in ((1, -1), (-1, 1)):
        CROSSINGS.append((C + sx * H, C + sy * (R - H), angle))
    else:
        CROSSINGS.append((C + sx * (R - H), C + sy * H, angle))


def rect(cx, cy, angle, half_len, half_wid):
    a = math.radians(angle)
    ca, sa = math.cos(a), math.sin(a)
    corners = [(-half_len, -half_wid), (half_len, -half_wid), (half_len, half_wid), (-half_len, half_wid)]
    return [(cx + x * ca - y * sa, cy + x * sa + y * ca) for x, y in corners]


def circle_path(cx, cy, r):
    return "M%s,%s a%s,%s 0 1,0 %s,0 a%s,%s 0 1,0 %s,0 Z" % (f(cx - r), f(cy), f(r), f(r), f(2 * r), f(r), f(r), f(-2 * r))


# ── SVG ──
def mark_svg():
    out = []
    out.append('<g fill="none" stroke-linejoin="miter">')
    for color, width in ((EDGE, OUTLINE), (GOLD, BAND)):
        out.append('  <polygon points="%s" stroke="%s" stroke-width="%s"/>' % (pts(DIAMOND), color, f(width)))
    for color, width in ((EDGE, OUTLINE), (CREAM, BAND)):
        out.append('  <polygon points="%s" stroke="%s" stroke-width="%s"/>' % (pts(SQUARE), color, f(width)))
    out.append("</g>")
    for cx, cy, angle in CROSSINGS:  # gold back over cream; the gold piece is longer, so no seam shows at its ends
        out.append('<polygon points="%s" fill="%s"/>' % (pts(rect(cx, cy, angle, PATCH, OUTLINE / 2)), EDGE))
        out.append('<polygon points="%s" fill="%s"/>' % (pts(rect(cx, cy, angle, PATCH + 1, BAND / 2)), GOLD))
    out.append('<circle cx="%s" cy="%s" r="6.6" fill="none" stroke="%s" stroke-width="1.6"/>' % (f(C), f(C), CREAM))
    out.append('<circle cx="%s" cy="%s" r="2.6" fill="%s"/>' % (f(C), f(C), GOLD))
    return "\n  ".join(out)


def icon_svg(size=512):
    return """<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 108 108">
  <!-- Generated by make_icon.py; do not edit by hand. -->
  <rect width="108" height="108" fill="%s"/>
  <circle cx="54" cy="54" r="46" fill="%s" fill-opacity="0.55"/>
  %s
</svg>
""" % (size, size, BG, GLOW, mark_svg())


# ── Android drawables ──
HEAD = """<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
"""


def stroke_path(points, color, width):
    return """    <path
        android:pathData="%s"
        android:strokeColor="%s"
        android:strokeWidth="%s"
        android:strokeLineJoin="miter" />
""" % (path(points), color, f(width))


def fill_path(data, color):
    return """    <path
        android:fillColor="%s"
        android:pathData="%s" />
""" % (color, data)


def background_xml():
    return HEAD + "    <!-- Generated by store/assets/make_icon.py -->\n" + fill_path("M0,0h108v108h-108z", BG) + """    <path
        android:fillAlpha="0.55"
        android:fillColor="%s"
        android:pathData="%s" />
</vector>
""" % (GLOW, circle_path(C, C, 46))


def foreground_xml():
    x = HEAD + "    <!-- Generated by store/assets/make_icon.py: the star that marks a quarter of a hizb, two squares woven. -->\n"
    x += stroke_path(DIAMOND, EDGE, OUTLINE) + stroke_path(DIAMOND, GOLD, BAND)
    x += stroke_path(SQUARE, EDGE, OUTLINE) + stroke_path(SQUARE, CREAM, BAND)
    for cx, cy, angle in CROSSINGS:
        x += fill_path(path(rect(cx, cy, angle, PATCH, OUTLINE / 2)), EDGE)
        x += fill_path(path(rect(cx, cy, angle, PATCH + 1, BAND / 2)), GOLD)
    x += """    <path
        android:pathData="%s"
        android:strokeColor="%s"
        android:strokeWidth="1.6" />
""" % (circle_path(C, C, 6.6), CREAM)
    x += fill_path(circle_path(C, C, 2.6), GOLD)
    return x + "</vector>\n"


def monochrome_xml():
    # One colour, so the bands of the two squares simply overlap; the system tints it.
    x = HEAD + "    <!-- Generated by store/assets/make_icon.py: the same star as one shape, for themed icons. -->\n"
    x += stroke_path(DIAMOND, "#FFFFFF", BAND) + stroke_path(SQUARE, "#FFFFFF", BAND)
    x += """    <path
        android:pathData="%s"
        android:strokeColor="#FFFFFF"
        android:strokeWidth="1.6" />
""" % circle_path(C, C, 6.6)
    x += fill_path(circle_path(C, C, 2.6), "#FFFFFF")
    return x + "</vector>\n"


# ── Feature graphic ──
def feature_html():
    html = """<!doctype html>
<html lang="ar" dir="rtl">
<head>
<meta charset="utf-8">
<title>Mutqan feature graphic 1024x500</title>
<!-- Generated by make_icon.py; the mark is the launcher icon's. -->
<style>
  @font-face { font-family: "Amiri"; font-weight: 700; src: url("../../quran/src/main/res/font/amiri_bold.ttf"); }
  @font-face { font-family: "Plex"; font-weight: 500; src: url("../../app/src/main/res/font/ibm_plex_sans_arabic_medium.ttf"); }
  html, body { margin: 0; padding: 0; }
  .stage {
    width: 1024px; height: 500px; overflow: hidden; position: relative; box-sizing: border-box;
    background: radial-gradient(circle at 28% 50%, @GLOW@ 0%, @BG@ 58%, #0E3228 100%);
    display: flex; align-items: center; justify-content: center; gap: 60px; color: @CREAM@;
  }
  .ring { position: absolute; border-radius: 50%; border: 2px solid rgba(244,237,220,.07); }
  .ring.a { width: 760px; height: 760px; left: -230px; top: -130px; }
  .ring.b { width: 520px; height: 520px; left: -110px; top: -10px; border-color: rgba(244,237,220,.09); }
  .mark { width: 340px; height: 340px; flex: none; position: relative; filter: drop-shadow(0 14px 26px rgba(0,0,0,.35)); }
  .text { position: relative; text-align: right; }
  .name { font: 700 170px/1 "Amiri", serif; margin: 0; }
  .tag { font: 500 38px/1.5 "Plex", sans-serif; margin: 10px 0 0; color: #E4DAC2; }
  .rule { width: 120px; height: 4px; background: @GOLD@; border-radius: 2px; margin: 22px 0 0 auto; }
  .en { font: 500 26px/1.4 "Plex", sans-serif; direction: ltr; text-align: right; margin: 16px 0 0; color: @GOLD@; letter-spacing: .04em; }
</style>
</head>
<body>
<div class="stage">
  <div class="ring a"></div><div class="ring b"></div>
  <svg class="mark" viewBox="14 14 80 80" xmlns="http://www.w3.org/2000/svg">
  @MARK@
  </svg>
  <div class="text">
    <h1 class="name">متقن</h1>
    <p class="tag">رفيقك في مراجعة حفظ القرآن</p>
    <div class="rule"></div>
    <p class="en">Mutqan · Quran revision companion</p>
  </div>
</div>
</body>
</html>
"""
    for key, value in (("@GLOW@", GLOW), ("@BG@", BG), ("@CREAM@", CREAM), ("@GOLD@", GOLD), ("@MARK@", mark_svg())):
        html = html.replace(key, value)
    return html


def write(rel, text):
    p = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with io.open(p, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote", rel)


def chrome_png(html_or_svg_path, out, width, height, scale=1):
    subprocess.run([
        CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=%s" % scale,
        "--window-size=%d,%d" % (width, height), "--screenshot=" + out, "file:///" + html_or_svg_path.replace("\\", "/"),
    ], check=True, capture_output=True)


def legacy_icons():
    """Android 7.0 and 7.1 know no adaptive icons: a rounded square and a round one, as WebP in each density."""
    from PIL import Image, ImageDraw
    sizes = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
    tmp = tempfile.mkdtemp()
    for density, px in sizes.items():
        big = px * 4
        page = os.path.join(tmp, "p%d.html" % px)
        with io.open(page, "w", encoding="utf-8") as fh:
            fh.write('<html><body style="margin:0"><img src="file:///%s" width="%d" height="%d" style="display:block"></body></html>'
                     % (os.path.join(ROOT, "store", "assets", "icon.svg").replace("\\", "/"), big, big))
        shot = os.path.join(tmp, "s%d.png" % px)
        chrome_png(page, shot, big, big)
        base = Image.open(shot).convert("RGBA")
        for name, radius in (("ic_launcher", 0.2), ("ic_launcher_round", 0.5)):
            mask = Image.new("L", (big, big), 0)
            ImageDraw.Draw(mask).rounded_rectangle((0, 0, big - 1, big - 1), radius=int(big * radius), fill=255)
            icon = Image.new("RGBA", (big, big), (0, 0, 0, 0))
            icon.paste(base, (0, 0), mask)
            icon = icon.resize((px, px), Image.LANCZOS)
            out = os.path.join(ROOT, "app", "src", "main", "res", "mipmap-" + density, name + ".webp")
            icon.save(out, "WEBP", lossless=True)
            print("wrote", os.path.relpath(out, ROOT))


if __name__ == "__main__":
    write(r"store\assets\icon.svg", icon_svg())
    write(r"store\assets\feature.html", feature_html())
    write(r"app\src\main\res\drawable\ic_launcher_background.xml", background_xml())
    write(r"app\src\main\res\drawable\ic_launcher_foreground.xml", foreground_xml())
    write(r"app\src\main\res\drawable\ic_launcher_monochrome.xml", monochrome_xml())
    assets = os.path.join(ROOT, "store", "assets")
    chrome_png(os.path.join(assets, "icon.svg"), os.path.join(assets, "icon-512.png"), 512, 512)
    chrome_png(os.path.join(assets, "feature.html"), os.path.join(assets, "feature-graphic-1024x500.png"), 1024, 500)
    legacy_icons()
